#!/usr/bin/env python3
"""Writes pc/core/api_names.txt: the names the platform layer must provide.

    python3 tools/pc/api_names.py [--out pc/core/api_names.txt]

From the library inventory (the library functions Capcom's code reaches,
by symbols and relocations of the matching build, never from library code):
the 243 functions, and the 208 library data objects (state variables of the
SDK that Capcom's code addresses by name) with the sizes of their symbols.
tools/pc/gen_stubs.py reads the file; run this again when the inventory
changes (it needs the matching build's ELFs in build/).
"""
import argparse
import csv
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT / "tools" / "pc"))
VARIADIC = {"printf", "sprintf", "scePrintf"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "pc" / "core" / "api_names.txt")
    a = ap.parse_args()
    tsv = ROOT / "build" / "pc" / "inventory.tsv"
    tsv.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([sys.executable, str(ROOT / "tools" / "port" / "lib_inventory.py"), "--tsv", str(tsv)],
                   check=True, cwd=ROOT, stdout=subprocess.DEVNULL)
    rows = list(csv.DictReader(tsv.open(), delimiter="\t"))
    from elftools.elf.elffile import ELFFile
    sizes: dict[tuple[str, str], int] = {}
    for mod in {r["module"] for r in rows}:
        with open(ROOT / "build" / f"{mod}.elf", "rb") as f:
            syms = [(s["st_value"], s["st_size"], s.name, s["st_shndx"])
                    for s in ELFFile(f).get_section_by_name(".symtab").iter_symbols()
                    if s.name and s["st_shndx"] not in ("SHN_UNDEF", "SHN_ABS")]
        syms.sort()
        for i, (addr, size, name, shndx) in enumerate(syms):
            if size == 0:       # the symbol has no size: the room up to the next object of its section
                nxt = next((a for a, _, _, sh in syms[i + 1:] if sh == shndx and a > addr), addr + 4)
                size = nxt - addr
            sizes[(mod, name)] = size
    funcs, data = {}, {}
    for r in rows:
        if r["piece"].startswith("data:"):
            n = sizes.get((r["module"], r["name"]), 0) or 4
            data[r["name"]] = max(data.get(r["name"], 0), n)
        elif r["piece"] != "sdk/crt0":              # __start is the program's entry; main.c is ours
            funcs[r["name"]] = r["piece"]
    out = ["# Generated by tools/pc/api_names.py. Do not edit.",
           "# NAME: a library function; NAME ...: variadic; NAME data SIZE: a library data object.",
           "# The names the stub layer provides (tools/pc/gen_stubs.py) until a file defines them."]
    for n in sorted(funcs):
        out.append(f"{n} ..." if n in VARIADIC else n)
    for n in sorted(data):
        out.append(f"{n} data {data[n]}")
    a.out.write_text("\n".join(out) + "\n")
    print(f"api_names: {len(funcs)} functions, {len(data)} data objects -> {a.out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
