#ifndef CONTENT_WPN_H
#define CONTENT_WPN_H

/*
 * What the game asks of the content core for a weapon type of its own.
 *
 * Dos has the weapon types 0 to 10. A new type (11 and up) has a motion set larger than Dos's 300 slots and attack rows of its own, so two
 * tables of the game's own memory, which cannot grow at their PS2 addresses, are asked of the platform layer instead:
 *
 *  - The motion table (gMotions, include/motion.h): the player's stride, the monsters' first index and the table's length, and the table
 *    and the first index of each motion group (gPlayerMotionGroupFirst). Each accessor is given the game's own value or table and returns
 *    it unchanged unless the content core made another layout (the stride a pack's weapon files need): then the table is in the arena,
 *    which a save state holds, and the monsters' slots follow the players' by the new stride.
 *  - The attack rows (PlayerAttack_Setup, PlayerAttack_Run): Pal_ContentAttackRows(type) is the cell that holds the pointer to the type's
 *    rows (what PlayerAttack_RowsPtr is for Dos's), or NULL for a type that has none, which is every type up to 10: Dos's rows, and the
 *    cases keyed by Dos's row ids, stay Dos's. A new type's ids are local to the type (an id is a u8: 256 rows at most), and a hit shape
 *    list number a row names is read from the type's own list table (Pal_ContentAttackHitShapes).
 */






























































































































































































































































#endif
