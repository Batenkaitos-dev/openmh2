#ifndef CONTENT_WTYPE_H
#define CONTENT_WTYPE_H

/*
 * The per-type tables Dos has for its 11 weapon classes, served for the classes 11 to 13 (the content core's class accessors).
 *
 * Dos indexes these tables by the weapon's class; a hunter of a class Dos lacks reads past the end of the array, the game's next data. The tables the pack's class rows (crows.tbl
 * version 2) carry are asked of the platform layer instead: each accessor is given the game's own array and returns it unchanged unless the pack has the table, then a table of 14
 * rows (Dos's 11, a row for each of the classes 11 to 13 that the pack's table holds; the multiplier's and the eye distance's arrays are the same 14 entries) in the content core's
 * memory. The macro that puts the call where the game indexes an array is in the file that declares it (window.h, equip_preview.c, player_draw.c), and the file that defines the array does
 * so after an #undef of its name.
 *
 *   the class multiplier (gWeaponClassMultipliers, s32)         Pal_ContentClassMult
 *   the equipment preview's eye distance (gEquipPreviewWpEyeZ, f32) Pal_ContentWpEyeZ
 *   the weapon poses (gWpPoseDrawn, gWpPoseDrawnAlt, gWpPoseSheathed, gWpPoseSharpen, WpPose = 6 f32) Pal_ContentWpPose
 *   the item box's sort key by class (gBoxSortClassKeys, s32)  Pal_ContentBoxClassKey
 *   the records' weapon genre by class (Weapon_IsInGenre)         Pal_ContentGenre
 *   the equipment preview's position and rotation rows (gEquipPreviewWpPos, gEquipPreviewWpRot) Pal_ContentPreviewPose
 *
 * The tables that have no source in the client's data (the hit sounds, the box sort keys, the class flags, the names, the start items) and the ones with a source that is not whole
 * (the class attack pair: one of its two columns is not Dos's in the client) stay open.
 */




































































































































































































































#endif
