#ifndef CONTENT_AREA_H
#define CONTENT_AREA_H

/*
 * The area tables of a content area (the content core).
 *
 * The game's per-area tables hold the areas 0 to 199 (the PS2's layout, which cannot grow). A content area (a pack's room or village,
 * with its own id: 200 and up) keeps its rows in the platform layer, found by the area id (the pack registers
 * rows by id: nothing is sized to the highest id). A site that indexes one of the tables by an area id reads it through AREA_AT: the row the platform layer
 * holds when the pack registered that id (200 and up), else the element of the game's table, the expression it always was (an id the pack
 * did not register, in range or not, reads the game's memory as it did).
 *
 * Off the content core AREA_AT is the index expression itself, so the PS2's build and the PC core without content are as they were.
 */



























































































































































































































































































































































































#define AREA_MODEL_BASE() ((*(s32 *)&gSysSettings.modelPack))

#define AREA_AT(tab, arr, id) ((arr)[id])

#define AREA_SEBANK_ROW(id) (id)


#endif
